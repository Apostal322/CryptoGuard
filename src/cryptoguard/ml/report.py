"""Render ML_EVALUATION.md from one training run (generated; never edit by hand)."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from cryptoguard.ml.sources import SOURCES


def _f(x: float | None, digits: int = 3) -> str:
    return "—" if x is None else f"{x:.{digits}f}"


def _ci(r: dict[str, Any], key: str) -> str:
    ci = (r.get("ci95") or {}).get(key)
    return f" [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else ""


def render_report(entry: dict[str, Any], out: dict[str, Any], manifest: dict[str, Any]) -> str:
    gate = entry["gate"]
    sel = entry["selected"]
    splits = manifest["splits"]
    L: list[str] = []
    add = L.append
    add("# ML evaluation (experimental, shadow mode only)\n")
    add(
        f"Generated by `cryptoguard ml train` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC; do not "
        f"edit by hand. Run `{entry['run_id']}`, code `{entry['git']}`, {entry['ml_version']}, "
        f"features `{entry['feature_set_version']}`. Training and evaluation took "
        f"{entry['seconds']} s on CPU.\n"
    )
    add("## Task\n")
    add(
        "Classify an Ethereum transaction as part of a phishing operation or not, from "
        "information available when it executed: the transaction, its receipt, and the "
        "sender's nonce and target's code at the previous block. Labels come from PTXPhish "
        "(NDSS 2025), reviewed by two security experts and independent of CryptoGuard. "
        "Many labelled phishing transactions are the *attacker's* (for ice phishing, the "
        "`transferFrom` that drains the victim), so this is not a pre-signing warning for a "
        "victim's own approval.\n"
    )
    add("## Data\n")
    add("| Source | Pinned commit | License | Use |")
    add("|---|---|---|---|")
    uses = {
        "ptxphish": "training and evaluation labels",
        "poison-hunter": "data card only",
        "forta": "data card only",
    }
    for name, s in SOURCES.items():
        add(
            f"| [{s.repository}](https://github.com/{s.repository}) | `{s.commit[:10]}` | "
            f"{s.license or 'none published (not redistributed)'} | {uses[name]} |"
        )
    add("")
    add(
        f"- Collected: {manifest['rows']} labelled transactions with chain data "
        f"(sample of {manifest.get('sample_rows', '?')}; "
        f"{manifest.get('rpc_requests_used', '?')} of 12,000 approved RPC requests used; "
        f"not found on chain: {manifest['not_found']}). Blocks "
        f"{manifest['block_range'][0]:,} to {manifest['block_range'][1]:,}."
    )
    add(
        "- Per subtype: " + ", ".join(f"{k} {v}" for k, v in manifest["label_counts"].items()) + "."
    )
    g = manifest["groups"]
    add(
        f"- Account groups (diagnostic): {g['groups']} groups, largest {g['largest_group_rows']} "
        f"rows, {g['mixed_label_groups']} mixed-label group(s) holding "
        f"{g['rows_in_mixed_groups']} rows; {g['phishing_rows_sharing_a_group']} phishing rows "
        "share infrastructure with another phishing row."
    )
    add("")
    add("## Splits\n")
    lo, hi = splits["window"]
    add(
        f"Study window: blocks {lo:,} to {hi:,}, where both classes occur (benign transactions "
        "outside it are excluded, or the era alone would separate the classes). Ordered by "
        f"block: validation from block {splits['boundaries']['validation_from_block']:,}, test "
        f"from {splits['boundaries']['test_from_block']:,}. Rows sharing a non-hub account with "
        f"an earlier split are dropped; hubs come from training rows only "
        f"({splits['hub_accounts_from_train']}).\n"
    )
    add("| Split | Benign | Phishing |")
    add("|---|---|---|")
    for name, counts in sorted(splits["counts"].items()):
        add(f"| {name} | {counts.get('0', 0)} | {counts.get('1', 0)} |")
    add("")
    add("## Results\n")
    add(
        "Hyperparameters, thresholds and the selected model were chosen on validation; test "
        "was scored once. AP = average precision (PR-AUC); intervals are 95% bootstrap "
        "intervals over test rows.\n"
    )
    neg = entry["test"]["rows"] - entry["test"]["positives"]
    add(
        f"Test rows: {entry['test']['rows']} ({entry['test']['positives']} phishing, {neg} benign; "
        f"phishing share {entry['test']['prevalence']:.2f}, so any ranking scores AP of at least "
        "that much — compare AP lift and the false-positive rate, measured on only "
        f"{neg} benign rows).\n"
    )
    add(
        "| Model | Features | Val log loss | Val AP | Test AP [95% CI] | Test AP lift "
        "| Test ROC-AUC | Test bal. acc. | Test recall [95% CI] | Test FPR [95% CI] |"
    )
    add("|---|---|---|---|---|---|---|---|---|---|")
    for r in entry["results"]:
        v, t = r["validation"], r["test"]
        is_sel = r["name"] == sel["name"] and r["feature_set"] == sel["feature_set"]
        loss = _f(v["log_loss"]) if r["kind"] != "rule" else "—"
        add(
            f"| {r['name']}{' (selected)' if is_sel else ''} | {r['feature_set'] or '—'} "
            f"| {loss} | {_f(v['average_precision'])} "
            f"| {_f(t['average_precision'])}{_ci(t, 'average_precision')} | {_f(t['ap_lift'])} "
            f"| {_f(t['roc_auc'])} | {_f(t['balanced_accuracy'])} "
            f"| {_f(t['recall'])}{_ci(t, 'recall')} "
            f"| {_f(t['false_positive_rate'])}{_ci(t, 'false_positive_rate')} |"
        )
    add("")
    st = entry["test"]
    add(
        f"Selected: **{sel['name']}** on `{sel['feature_set']}` features, {sel['params']}, "
        f"threshold {sel['threshold']:.3f}. Test confusion: {st['confusion']}.\n"
    )
    if st.get("recall_by_family"):
        add(
            "Test recall by phishing family: "
            + ", ".join(f"{k} {v:.2f}" for k, v in st["recall_by_family"].items())
            + ".\n"
        )
    add("### Promotion gate (shadow mode)\n")
    add(
        f"- On validation, close at least {gate['required_gap_reduction']:.0%} of the AP gap "
        f"between the best baseline ({gate['best_baseline_validation_ap']:.3f}) and 1.0 "
        f"(closed: {gate['validation_gap_closed']:.0%}): **{gate['validation_beats_baselines']}**."
    )
    add(
        f"- Test AP interval must lie above the best baseline's test AP "
        f"({gate['best_baseline_test_ap']:.3f}): **{gate['test_interval_above_best_baseline']}**."
    )
    add(f"- Validated for shadow mode: **{gate['validated_for_shadow']}**.\n")
    add("### What the selected model relies on\n")
    add("Permutation importance on validation (increase in log loss when a feature is shuffled):\n")
    for imp in out["importance"][:10]:
        add(f"- `{imp['feature']}`: {imp['mean']:.3f} ± {imp['std']:.3f}")
    add("")
    add("### Errors on test\n")
    fn, fp = out["errors"]["false_negatives"], out["errors"]["false_positives"]
    add(f"Missed phishing (lowest scores first, up to 15 of {st['confusion']['fn']}):\n")
    for e in fn:
        add(f"- `{e['tx_hash']}` {e['family']}/{e['subtype']}, score {e['score']:.3f}")
    add(f"\nBenign flagged (highest scores first, up to 15 of {st['confusion']['fp']}):\n")
    for e in fp:
        add(f"- `{e['tx_hash']}` {e['subtype']}, score {e['score']:.3f}")
    add("")
    add("## Limitations\n")
    for item in (
        "One labelled source. PTXPhish's benign class is transactions of prominent accounts "
        '("KOL") and developers, not a random sample of Ethereum users; precision on real '
        "traffic, where phishing is far rarer than here, will be much lower than measured.",
        "The `no_identity` rows show how much depends on who sends a transaction (long "
        "histories, vanity addresses) rather than what it does; those signals partly reflect "
        "how the dataset was built.",
        "Small test split after the time window and account purge; intervals are wide.",
        "The CryptoGuard comparison is a transaction-level proxy of its signals, not its "
        "wallet-centric detectors, which need wallet history this dataset lacks.",
        "Features use the receipt (logs of the executed transaction). Scoring a transaction "
        "before it is signed would need a simulation, which is not implemented.",
        "Not independently reviewed. The model never creates findings (shadow mode only).",
    ):
        add(f"- {item}")
    add("")
    return "\n".join(L)
