"""Render ``CAMPAIGN_EVALUATION.md`` from a ``CampaignEvaluation`` (every number computed)."""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from cryptoguard.campaigns.evaluate import CampaignEvaluation, ClusterStats


def _strings(value: object) -> list[str]:
    return [str(v) for v in value] if isinstance(value, list) else []


def _dicts(value: object) -> list[dict[str, object]]:
    return [v for v in value if isinstance(v, dict)] if isinstance(value, list) else []


def _conclusions(ev: CampaignEvaluation) -> list[str]:
    d0 = ev.scenarios["monitored wallets only"]["D_combined (default)"]
    d1 = ev.scenarios["plus expansion"]["D_combined (default)"]
    x1 = ev.scenarios["plus expansion"]["X_no_guards (common contracts merge, no hub cap)"]
    p = ev.prior_context
    with_lead = [i for i in ev.incidents if i.lead_blocks is not None]
    earlier = [
        i
        for i in with_lead
        if i.existing_detector_lead_blocks is None
        or (i.lead_blocks or 0) > i.existing_detector_lead_blocks
    ]
    by_kind = {
        k: ev.scenarios["plus expansion"][name].multi_wallet_clusters
        for k, name in (
            ("signer", "A_signer_only"),
            ("lookalike", "B_lookalike_only"),
            ("transaction", "C_transaction_only"),
        )
    }
    r = ev.ranking
    overlaps = [
        v
        for v in (
            r.mean_top5_overlap_heat_vs_hops,
            r.mean_top5_overlap_heat_vs_ppr,
            r.mean_top5_overlap_heat_vs_shared_neighbours,
        )
        if v is not None
    ]
    out = [
        f"- **Cross-wallet links exist in real data.** With monitored wallets alone, "
        f"{d0.multi_wallet_clusters} candidate clusters span more than one wallet; with the "
        f"bounded expansion, {d1.multi_wallet_clusters} (largest: {d1.largest_cluster_attempts} "
        f"attempts on {d1.largest_cluster_wallets} wallets). Multi-wallet clusters by single "
        f"link type: shared signer {by_kind['signer']}, shared planting transaction "
        f"{by_kind['transaction']}, reused lookalike {by_kind['lookalike']}.",
        f"- **Context at the time of an attempt.** {p['signer_already_seen_on_other_wallets']} of "
        f"{p['attempts_checked']} attempts on monitored wallets used a planting signer already "
        "seen on another wallet earlier (point in time).",
        f"- **No earlier warning.** For {len(with_lead)} of {len(ev.incidents)} thefts the "
        "recipient's cluster spanned several wallets before the theft, but "
        + (
            "never earlier than the existing detector's own warning."
            if not earlier
            else f"earlier than the existing detector in: {', '.join(i.case_id for i in earlier)}."
        ),
        f"- **Guards matter.** Without them (popular contracts and every shared entity "
        f"merging), the largest cluster grows from {d1.largest_cluster_attempts} to "
        f"{x1.largest_cluster_attempts} attempts and from {d1.largest_cluster_wallets} to "
        f"{x1.largest_cluster_wallets} wallets; block proximity alone would merge "
        f"{ev.temporal['pairs_not_already_linked']} otherwise unlinked pairs.",
        "- **Diffusion adds no ranking information here**: its top-5 agrees with simpler "
        f"methods on {min(overlaps) if overlaps else 'n/a'}-{max(overlaps) if overlaps else 'n/a'} "
        "of 5 attempts on average."
        if overlaps and min(overlaps) >= 4
        else "- **Diffusion ranks differently** from simpler methods on this data; the "
        "difference is not validated as useful.",
        "- **Spectral gap is redundant** with articulation points, which identify the same "
        "weakly connected (chained) clusters exactly and name the joining point."
        if ev.spectral.gap_separates
        else "- **Spectral gap does not separate** chained clusters; articulation points do.",
    ]
    return out


def _row(name: str, s: ClusterStats) -> str:
    return (
        f"| {name} | {s.attempts} | {s.clusters} | {s.multi_wallet_clusters} | "
        f"{s.largest_cluster_attempts} / {s.largest_cluster_wallets} | {s.tentative_clusters} | "
        f"{s.hub_entities} | {s.unclustered} |"
    )


HEADER = (
    "| Configuration | Attempts | Clusters | Multi-wallet | Largest (attempts / wallets) "
    "| Tentative | Hub entities | Unclustered |\n|---|---|---|---|---|---|---|---|"
)


def render(ev: CampaignEvaluation) -> str:
    x = ev.expansion
    out: list[str] = [
        "# Campaign evaluation",
        "",
        "Generated by `cryptoguard campaigns evaluate --write-report CAMPAIGN_EVALUATION.md` from "
        f"recorded data; do not edit by hand. Generated {ev.generated_at}; clustering "
        f"`{ev.algorithm_version}`.",
        "",
        "## 1. Research question",
        "",
        "Can CryptoGuard link address-poisoning attempts on different wallets through shared, "
        "verifiable planting infrastructure, without merging unrelated attackers, and does "
        "that add information beyond per-wallet findings?",
        "",
        "## 2. Data",
        "",
        "- **Attempts from monitored wallets**: the 4 incident fixtures (cut one block before "
        "each theft) and the recorded background wallets of `EVALUATION.md`, run through the "
        "existing poisoning detector. Fixtures (SHA-256 of canonical content):",
        "",
    ]
    out += [f"  - `{k}`: `{v[:16]}…`" for k, v in sorted(ev.subjects.items())]
    out += [
        "",
        "- **Expansion** (`replay/campaign_cases/expansion.json`, canonical SHA-256 "
        f"`{(ev.expansion_sha256 or 'n/a')[:16]}…`): recorded {x.get('recorded_at')} with "
        f"{x.get('recorded_with')}, cutoff block {x.get('cutoff_block')} "
        f"(hash `{str(x.get('cutoff_block_hash'))[:18]}…`), {x.get('requests')} RPC requests "
        f"in {x.get('seconds')} s; stopped: {x.get('stopped') or 'no (all planned tasks ran)'}.",
        f"  Tasks by kind: {x.get('by_kind')}. Truncation notes: {x.get('truncations')}.",
        f"  Requests per seed attempt: {x.get('requests_per_seed_attempt')}; per verified new "
        f"attempt: {x.get('requests_per_verified_attempt')}.",
        "- **Inclusion**: an expanded event counts as an attempt only if the candidate target "
        "had sent a nonzero Transfer to an address the lookalike resembles (the detector's "
        "thresholds) within 100 blocks before it. **Exclusion**: everything else is kept as an "
        "unverified candidate and never clustered.",
        "- **Not attempted**: " + "; ".join(_strings(x.get("not_attempted"))) + ".",
        "",
        "## 3. Ground truth",
        "",
        "There is **no independent label** of which attempts share an operator: public reports "
        "describe single thefts, not attacker infrastructure. Pairwise precision/recall, ARI or "
        "NMI would have to score these rules against their own output, so none is reported. "
        "Incident manifests are used only to check, after the fact, where each theft's recipient "
        "ended up.",
        "",
        "## 4. Relationship definitions",
        "",
        "Planting-side entities only (never the targeted wallet): planting transaction "
        "(directly observed), lookalike and verified signer (strongly supported, merge), narrow "
        "token contract and deployer (tentative, context only), popular token contracts and "
        "block proximity (insufficient). A signer that planted more than 25 different lookalikes "
        "is a hub: reported, never merged. See `campaigns/relations.py` and DETECTION_METHODS.md.",
        "",
        "## 5. Results: ablations",
        "",
    ]
    for scenario, rows in ev.scenarios.items():
        out += [f"### {scenario}", "", HEADER]
        out += [_row(name, s) for name, s in rows.items()]
        out.append("")
    out += [
        "`X_no_guards` is an over-clustering probe, not a candidate configuration: it merges "
        "through every shared entity, including popular token contracts.",
        "",
        "### Hub-guard sensitivity (D, with expansion)",
        "",
        HEADER.replace("Configuration", "Max lookalikes per signer"),
    ]
    out += [_row(cap, s) for cap, s in ev.hub_sensitivity.items()]
    t = ev.temporal
    out += [
        "",
        f"### Ablation F: block proximity (within {t['window_blocks']} blocks, different wallets)",
        "",
        f"{t['cross_wallet_pairs_within_window']} cross-wallet attempt pairs fall within the "
        f"window; {t['pairs_not_already_linked']} of them are not linked by any infrastructure. "
        f"Merging on proximity would produce {t['groups_if_merged']} groups, the largest with "
        f"{t['largest_group_if_merged']} attempts. Proximity is therefore kept as a reported "
        "weak feature only.",
        "",
        "## 6. What the analysis adds over per-wallet findings",
        "",
    ]
    out += [f"- {k.replace('_', ' ')}: {v}" for k, v in ev.added_information.items()]
    out += ["", "Multi-wallet clusters (default configuration, with expansion):", ""]
    out.append(
        "| Campaign | Attempts | Wallets (monitored) | Lookalikes | Signers | Blocks "
        "| Structure | Confidence | Merged by |"
    )
    out.append("|---|---|---|---|---|---|---|---|---|")
    for e in ev.real_examples:
        out.append(
            f"| `{e['campaign_id']}` | {e['attempts']} | {e['wallets']} ({e['monitored_wallets']}) "
            f"| {e['lookalikes']} | {e['signers']} | {e['blocks']} | {e['structure']} | "
            f"{e['confidence']} | {', '.join(e['merging'])} |"  # type: ignore[arg-type]
        )
    out += [
        "",
        "### New attempts with already-known infrastructure (point in time)",
        "",
        "For each attempt on a monitored wallet, using only data from strictly earlier blocks: "
        "had its planting signer or lookalike already been seen in attempts on another wallet?",
        "",
        f"- Attempts checked: {ev.prior_context['attempts_checked']}; signer already seen "
        f"elsewhere: {ev.prior_context['signer_already_seen_on_other_wallets']}; lookalike "
        f"already seen elsewhere: {ev.prior_context['lookalike_already_seen_on_other_wallets']}; "
        f"monitored wallets concerned: {ev.prior_context['monitored_wallets_affected']}.",
        "",
        "| Wallet | Block | Shared | Other wallets before | First seen block |",
        "|---|---|---|---|---|",
        *[
            f"| {e['subject']} | {e['block']} | {e['shared']} | {e['other_wallets_before']} | "
            f"{e['first_seen_block']} |"
            for e in _dicts(ev.prior_context.get("examples"))
        ],
        "",
        "## 7. Point in time: before each theft",
        "",
        "Each row uses only attempts and expansion tasks seeded at or before the block before "
        "the theft; the recipient (from the manifest) is used only to look up the result.",
        "",
        "| Incident | Cutoff | Recipient seen as lookalike | Its cluster: wallets / confidence "
        "| Multi-wallet since block | Lead (blocks) | Existing detector lead "
        "| Inputs after cutoff |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i in ev.incidents:
        existing = i.existing_detector_lead_blocks
        out.append(
            f"| {i.case_id} | {i.cutoff_block} | {'yes' if i.recipient_in_attempts else 'no'} | "
            f"{i.cluster_wallets} / {i.cluster_confidence or '-'} | "
            f"{i.first_multi_wallet_block or '-'} | "
            f"{i.lead_blocks if i.lead_blocks is not None else '-'} | "
            f"{existing if existing is not None else '-'} | "
            f"{i.inputs_after_cutoff} |"
        )
    r, s = ev.ranking, ev.spectral
    out += [
        "",
        "## 8. Mathematical methods (ablations G and H)",
        "",
        f"- **G, diffusion**: {r.note} Over {r.clusters_compared} clusters, mean top-5 overlap of "
        f"heat diffusion with hop distance {r.mean_top5_overlap_heat_vs_hops}, with personalized "
        f"PageRank {r.mean_top5_overlap_heat_vs_ppr}, with shared-neighbour counts "
        f"{r.mean_top5_overlap_heat_vs_shared_neighbours} (of 5).",
        f"- **H, spectral**: {s.note} {s.clusters} clusters, {s.chained} chained; mean gap "
        f"chained {s.mean_gap_chained} vs other {s.mean_gap_other}; the gap alone separates "
        f"the two groups: {'yes' if s.gap_separates else 'no'}.",
        "",
        "## 9. Cost",
        "",
        "Clustering on SYNTHETIC attempts (cost only, says nothing about detection):",
        "",
        "| Attempts | Seconds | Peak traced memory (KiB) | Clusters |",
        "|---|---|---|---|",
    ]
    out += [f"| {p.attempts} | {p.seconds} | {p.peak_kib} | {p.clusters} |" for p in ev.scale]
    out += [
        "",
        "## 10. Leakage checks",
        "",
        "- Tests: future attempts cannot change clusters at an earlier cutoff "
        "(`test_future_attempts_cannot_change_an_earlier_cutoff`); deployers known only after a "
        "cutoff are ignored; expansion tasks seeded after a cutoff are unusable before it "
        "(`test_tasks_seeded_after_a_cutoff_are_not_usable_before_it`); expansion never reads a "
        "block after its cutoff (`test_nothing_after_the_cutoff_is_read`).",
        "- Incident rows above: inputs dated after the cutoff = "
        + ", ".join(str(i.inputs_after_cutoff) for i in ev.incidents)
        + " (must all be 0).",
        "- The expansion was recorded once at the latest cutoff and filtered per incident. "
        "Filtering never adds later information, but a signer's newest-first transaction cap "
        "means an earlier cutoff can see fewer events than a recording made at that time.",
        "",
        "## 11. Conclusions (computed from the tables above)",
        "",
        *_conclusions(ev),
        "",
        "## 12. Limitations",
        "",
        "- No ground truth for common control; every cluster is a candidate grouping.",
        "- Signer windows are about 150 blocks each side of one known attempt, capped at 6 "
        "transactions per signer: the signers seen here sign far more, so expansion is a small "
        "sample of their activity, not a census.",
        "- Funding sources (incoming ETH) and factory-created contracts are invisible over "
        "standard JSON-RPC; a shared funder or deployer may exist without being seen.",
        "- Background wallets were sampled excluding contracts and very busy wallets.",
        "- Verification only checks ERC-20 payments within 100 blocks; targets whose real "
        "payment was native ETH or earlier remain unverified candidates.",
        "",
    ]
    return "\n".join(out)
