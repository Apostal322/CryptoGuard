"""Render replay results as the EVALUATION.md report. Every number comes from a replay run."""

from __future__ import annotations

from datetime import UTC, datetime

from cryptoguard.replay.engine import ReplayResult

OUTCOME_LABEL = {
    "early_warning": "Early warning",
    "post_incident_only": "Post-incident classification only",
    "not_detected": "Not detected",
}


def _lead(seconds: int | None, blocks: int | None) -> str:
    if blocks is None:
        return "—"
    if seconds is None:
        return f"{blocks} blocks"
    return f"{blocks} blocks (~{seconds // 60} min)"


def render_markdown(results: list[ReplayResult], *, generated_at: datetime | None = None) -> str:
    generated = (generated_at or datetime.now(UTC)).strftime("%Y-%m-%d %H:%M UTC")
    out: list[str] = [
        "# Evaluation",
        "",
        "Generated by `cryptoguard replay run --write-report` from recorded fixtures; do not edit "
        f"by hand. Generated {generated}.",
        "",
        "## Methodology",
        "",
        "- **Ground truth** comes from public incident reports, cross-checked on-chain, and is "
        "stored in each case's `manifest.json`. It is used only to score detector output.",
        "- **Detector input** is a fixture recorded once from an RPC provider (`fixture.json`, "
        "hash below): all ERC-20 transfers of the wallet in a fixed window, transaction signers, "
        "and every wallet-signed transaction (found by nonce bisection, not by searching where "
        "the answer is).",
        "- **Point in time**: the detector is evaluated at every block where new data appears "
        "before the harmful block, seeing only records at or before that block. This is "
        "exhaustive for finding the earliest possible warning.",
        "- **A warning** means rule CG-POI-001 or CG-POI-003 on the address that later received "
        "the funds. A finding that appears only once the harmful transfer is visible is reported "
        "as post-incident classification, never as early detection.",
        "- **Visibility levels** are evaluated separately: ERC-20 data only, and ERC-20 data plus "
        "the wallet's own signed transactions (what the live snapshot pipeline now sees).",
        "",
        "## Results",
        "",
        "| Case | Visibility | Outcome | First warning | Lead time | Other addresses flagged |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        for v in r.results:
            warn = (
                f"block {v.first_warning.block_number} ({v.first_warning.rule_id}, "
                f"{v.first_warning.severity}/{v.first_warning.confidence})"
                if v.first_warning
                else "—"
            )
            out.append(
                f"| {r.case_id} | {v.visibility.value} | {OUTCOME_LABEL[v.outcome]} | {warn} | "
                f"{_lead(v.lead_time_seconds, v.lead_time_blocks)} | "
                f"{v.other_addresses_flagged_before_harm} |"
            )
    for r in results:
        out += [
            "",
            f"## {r.title}",
            "",
            f"- Case `{r.case_id}`; harmful transaction `{r.harm_transaction}` at block "
            f"{r.harm_block}.",
            f"- Fixture: window {r.window_from_block}..{r.window_to_block}, "
            f"{r.transfers_in_fixture} ERC-20 transfers, {r.wallet_transactions_in_fixture} "
            f"wallet-signed transactions; recorded {r.recorded_at} with {r.recorded_with} "
            f"({r.rpc_requests_when_recorded} RPC requests); SHA-256 `{r.fixture_sha256}`.",
            f"- Detector `address-poisoning` {r.detector_version}, ruleset {r.ruleset_version}; "
            f"replay runtime {r.runtime_ms} ms, peak traced memory {r.peak_memory_kib} KiB, "
            f"{r.rpc_requests_during_replay} RPC requests during replay.",
            "",
        ]
        for v in r.results:
            out += [
                f"### {v.visibility.value}: {OUTCOME_LABEL[v.outcome]}",
                "",
                v.description,
                "",
                v.explanation,
                "",
            ]
            if v.first_warning:
                out.append(f"Signals at the first warning: {', '.join(v.first_warning.signals)}.")
                out.append("")
            if v.at_harm_block:
                out.append(
                    f"At the harmful block: {v.at_harm_block.rule_id} "
                    f"({v.at_harm_block.severity}/{v.at_harm_block.confidence}), signals "
                    f"{', '.join(v.at_harm_block.signals)}."
                )
                out.append("")
            out.append(f"Checkpoints evaluated: {v.checkpoints_evaluated}.")
            out.append("")
        out += ["### Leakage checks", ""]
        out += [
            f"- {'PASS' if c.passed else 'FAIL'} `{c.check}`: {c.detail}" for c in r.leakage_checks
        ]
        out += ["", "### Limitations", ""]
        out += [f"- {item}" for item in r.limitations]
    out += [
        "",
        "## What these results do not show",
        "",
        "- With this few cases, no detection rate, precision or false-positive rate can be "
        "estimated; results are case studies, not benchmarks.",
        "- Every case here was selected because it was publicly reported, which biases toward "
        "large, visible incidents.",
        "",
    ]
    return "\n".join(out)
